import networkx as nx

from sklearn.preprocessing import StandardScaler
from factor_analyzer import FactorAnalyzer

data = pd.read_csv("customer.csv")

data_num = data[["age", "spending"]].dropna()

scaler = StandardScaler()
data_scaled = scaler.fit_transform(data_num)

PFA = FactorAnalyzer(
    n_factors=1,
    rotation=None,
    method="principal"
)

PFA.fit(data_scaled)

loads = PFA.loadings_

loading_df = pd.DataFrame(
    loads,
    index=data_num.columns,
    columns=["PA1"]
)

print("FACTOR LOADINGS")
print(loading_df.round(4))

# ==========================================
# MEMBUAT DIAGRAM FACTOR ANALYSIS
# ==========================================

G = nx.DiGraph()

G.add_node("PA1", pos=(2, 0))

G.add_node("age", pos=(0, -1))
G.add_node("spending", pos=(0, 1))

for variable in data_num.columns:
    G.add_edge("PA1", variable)

pos = nx.get_node_attributes(G, "pos")

plt.figure(figsize=(9, 6))

nx.draw_networkx_nodes(
    G, pos,
    node_size=2200,
    node_color="white",
    edgecolors="black"
)

nx.draw_networkx_labels(
    G, pos,
    font_size=11
)

nx.draw_networkx_edges(
    G, pos,
    arrows=True,
    arrowstyle="->",
    arrowsize=20,
    width=1.5,
    edge_color="black"
)

for variable in data_num.columns:
    x1, y1 = pos["PA1"]
    x2, y2 = pos[variable]

    loading = loading_df.loc[variable, "PA1"]

    plt.text(
        (x1 + x2) / 2,
        (y1 + y2) / 2,
        f"{loading:.3f}",
        fontsize=11,
        ha="center",
        va="center",
        bbox=dict(facecolor="white", edgecolor="none")
    )

plt.title("Factor Analysis", fontsize=16, fontweight="bold")

plt.axis("off")
plt.tight_layout()
plt.show()

