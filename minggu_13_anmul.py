# 5. BARTLETT'S TEST OF SPHERICITY

n = len(data_num)
p = data_num.shape[1]

R = data_num.corr().values

det_R = np.linalg.det(R)

if det_R > 0:

    chi_square = -(n - 1 - (2*p + 5)/6) * np.log(det_R)

    df = p * (p - 1) / 2

    p_value = chi2.sf(chi_square, df)

    print("\nBARTLETT'S TEST")

    print("Chi-square:", chi_square)
    print("Degrees of freedom:", df)
    print("P-value:", p_value)

    if p_value < 0.05:
        print("H0 ditolak: terdapat korelasi antarvariabel")
    else:
        print("H0 tidak ditolak")

else:
    print("Matriks korelasi tidak dapat digunakan untuk uji Bartlett")


